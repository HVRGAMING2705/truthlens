texts = REAL + FAKE
y = np.array([0]*len(REAL) + [1]*len(FAKE))  # 1 = fake
vec = TfidfVectorizer(sublinear_tf=True, lowercase=True)
X = vec.fit_transform(texts)
model = LogisticRegression(C=1.0, max_iter=1000).fit(X, y)
skf = StratifiedKFold(5, shuffle=True, random_state=42)
pred_cv = cross_val_predict(LogisticRegression(C=1.0, max_iter=1000), X, y, cv=skf)
proba_cv = cross_val_predict(LogisticRegression(C=1.0, max_iter=1000), X, y, cv=skf, method="predict_proba")[:, 1]
acc = float(accuracy_score(y, pred_cv)); auc = float(roc_auc_score(y, proba_cv))
base = float(max(y.mean(), 1-y.mean()))
print(f"n={len(texts)} real={len(REAL)} fake={len(FAKE)} vocab={len(vec.vocabulary_)}")
print(f"CV accuracy={acc:.3f} AUC={auc:.3f} baseline={base:.3f}")
mj = {"vocabulary": vec.vocabulary_, "idf": vec.idf_.tolist(),
      "coef": model.coef_[0].tolist(), "intercept": float(model.intercept_[0]),
      "metrics": {"cv_accuracy": acc, "cv_auc": auc, "baseline_accuracy": base,
                  "n": len(texts), "n_real": len(REAL), "n_fake": len(FAKE),
                  "vocab": len(vec.vocabulary_)}}
with open("model.json", "w") as f: json.dump(mj, f, indent=1)

def py_prob(text):
    v = vec.transform([text])
    return float(model.predict_proba(v)[0][1])
